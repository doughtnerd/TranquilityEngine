// Generates the King of Pirates models, textures and audio, deterministically (seeded RNG, no clock).
// Usage: node samples/pirates/tools/generate.mjs
import { mkdirSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { makeAudio } from "./audio.mjs";
import { makeModels, MTL } from "./models.mjs";
import { makeTextures } from "./textures.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

/** The 8 team colours (red, blue, green, yellow, purple, orange, teal, pink) used for the sail variants. */
export const TEAM_COLORS = [
  [214, 60, 56],
  [58, 112, 214],
  [62, 176, 82],
  [236, 200, 52],
  [150, 86, 200],
  [238, 138, 44],
  [48, 184, 188],
  [232, 112, 170],
];

function write(dir, name, data) {
  mkdirSync(join(root, dir), { recursive: true });
  writeFileSync(join(root, dir, name), data);
}
function clean(dir, keep) {
  try {
    for (const f of readdirSync(join(root, dir))) if (!keep.has(f)) rmSync(join(root, dir, f));
  } catch {}
}

const models = makeModels();
const textures = makeTextures(TEAM_COLORS);
const audio = makeAudio();

clean("models", new Set([...Object.keys(models).map((n) => `${n}.obj`), "pirates.mtl"]));
clean("textures", new Set(Object.keys(textures)));
clean("audio", new Set(Object.keys(audio)));

write("models", "pirates.mtl", MTL);
const report = [];
for (const [name, mesh] of Object.entries(models)) {
  const obj = mesh.toObj("pirates.mtl", `King of Pirates: ${name} (generated by tools/generate.mjs)`);
  write("models", `${name}.obj`, obj);
  const tris = obj.split("\n").filter((l) => l.startsWith("f ")).length;
  report.push({ kind: "model", file: `models/${name}.obj`, tris });
}
for (const [name, data] of Object.entries(textures)) {
  write("textures", name, data);
  report.push({ kind: "texture", file: `textures/${name}` });
}
for (const [name, data] of Object.entries(audio)) {
  write("audio", name, data);
  report.push({ kind: "audio", file: `audio/${name}` });
}

let total = 0;
for (const r of report) {
  r.bytes = statSync(join(root, r.file)).size;
  total += r.bytes;
  console.log(`${r.file.padEnd(34)} ${String(r.bytes).padStart(8)} B${r.tris ? `  ${r.tris} tris` : ""}`);
}
console.log(`total ${(total / 1024).toFixed(1)} KiB in ${report.length} files`);
