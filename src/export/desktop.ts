// Desktop packages (ADR 0041): a Tauri app around a web build. The exporter writes the web build
// to `<out>/web/` and a generated Tauri project to `<out>/src-tauri/` whose window loads it; `tauri
// build` (Rust toolchain needed) then makes installers. The project is generated, not copied from
// the editor's src-tauri/: a game needs only the fs plugin, for saves in its app data folder
// (ADR 0024), and its own name, identifier, window size and icon. No file access here (node.ts
// writes the files), so the generated text is easy to test.
import type { ProjectSettingsInput } from "../engine";

/** Optional build settings in project.json under `build` (read by the exporter only). */
export interface BuildSettings {
  /** A square PNG or SVG in the project for the app icon; default: a neutral generated icon. */
  icon?: string;
  /** Reverse-DNS app identifier (where saves go, and the installer's id); default `com.myco.game.<name>`. */
  identifier?: string;
  /** App version, `x.y.z`; default 0.1.0. */
  version?: string;
}

export interface DesktopOptions {
  /** The product name (project.json's `name`). */
  name: string;
  settings: ProjectSettingsInput & { build?: BuildSettings };
}

/** Lowercase letters, digits and dashes, from a name: for crate names and identifiers. */
export function slug(name: string): string {
  const s = name
    .normalize("NFKD")
    .replace(/[^\w\s-]/g, "")
    .trim()
    .toLowerCase()
    .replace(/[\s_-]+/g, "-")
    .replace(/^-+|-+$/g, "");
  return /^[a-z]/.test(s) ? s : `game-${s || "app"}`;
}

/** The app identifier: `build.identifier`, else `com.myco.game.<slug>`. */
export function appIdentifier(options: DesktopOptions): string {
  const given = options.settings.build?.identifier;
  if (given) {
    if (!/^[A-Za-z][\w-]*(\.[A-Za-z][\w-]*)+$/.test(given)) throw new Error(`project.json's build.identifier "${given}" isn't a reverse-DNS name like com.example.mygame.`);
    return given;
  }
  return `com.myco.game.${slug(options.name).replace(/-/g, "")}`;
}

/** The app version: `build.version` if it's x.y.z, else 0.1.0. */
export function appVersion(options: DesktopOptions): string {
  const v = options.settings.build?.version;
  if (v === undefined) return "0.1.0";
  if (!/^\d+\.\d+\.\d+$/.test(v)) throw new Error(`project.json's build.version "${v}" must look like 1.2.3.`);
  return v;
}

/** The icon files `tauri icon` makes and the bundle lists. */
export const ICON_FILES = ["icons/32x32.png", "icons/128x128.png", "icons/128x128@2x.png", "icons/icon.icns", "icons/icon.ico"];

/** The generated Tauri project's files, by path under `src-tauri/` (icons aside: `tauri icon` makes those). */
export function desktopProjectFiles(options: DesktopOptions): Map<string, string> {
  const crate = slug(options.name);
  const lib = `${crate.replace(/-/g, "_")}_lib`;
  const display = options.settings.display ?? {};
  const config = {
    $schema: "https://schema.tauri.app/config/2",
    productName: options.name,
    version: appVersion(options),
    identifier: appIdentifier(options),
    build: { frontendDist: "../web" },
    app: {
      windows: [{ title: options.name, url: "index.html", width: display.width ?? 1280, height: display.height ?? 720, resizable: true, fullscreen: false, center: true }],
      security: { csp: null },
    },
    bundle: { active: true, targets: "all", icon: ICON_FILES },
  };
  const files = new Map<string, string>();
  files.set("tauri.conf.json", `${JSON.stringify(config, null, 2)}\n`);
  files.set(
    "Cargo.toml",
    `# Generated by \`npm run export -- --target desktop\` (Myco Engine, ADR 0041): the desktop shell of ${JSON.stringify(options.name)}.
[package]
name = "${crate}"
version = "${appVersion(options)}"
edition = "2021"

[lib]
name = "${lib}"
crate-type = ["staticlib", "cdylib", "rlib"]

[build-dependencies]
tauri-build = { version = "2", features = [] }

[dependencies]
tauri = { version = "2", features = [] }
tauri-plugin-fs = "2"

[profile.release]
codegen-units = 1
lto = true
opt-level = "s"
strip = true
`,
  );
  files.set("build.rs", "fn main() {\n    tauri_build::build()\n}\n");
  files.set(
    "src/main.rs",
    `// Prevents an extra console window on Windows in release builds.
#![cfg_attr(not(debug_assertions), windows_subsystem = "windows")]

fn main() {
    ${lib}::run();
}
`,
  );
  files.set(
    "src/lib.rs",
    `// The game's window loads the web build (../web). The fs plugin keeps saves and settings in the
// app data folder (Myco Engine's Storage, ADR 0024).
#[cfg_attr(mobile, tauri::mobile_entry_point)]
pub fn run() {
    tauri::Builder::default()
        .plugin(tauri_plugin_fs::init())
        .run(tauri::generate_context!())
        .expect("error while running the game");
}
`,
  );
  files.set(
    "capabilities/default.json",
    `${JSON.stringify(
      {
        $schema: "../gen/schemas/desktop-schema.json",
        identifier: "default",
        description: "The game's window. Storage (ADR 0024) reads and writes files in the app data folder, and nowhere else.",
        windows: ["main"],
        permissions: ["core:default", "fs:default", "fs:read-all", "fs:write-all", "fs:allow-appdata-read-recursive", "fs:allow-appdata-write-recursive"],
      },
      null,
      2,
    )}\n`,
  );
  files.set(".gitignore", "/target/\n/gen/schemas\n");
  return files;
}

