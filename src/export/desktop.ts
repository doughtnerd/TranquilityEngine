// Desktop packages (ADR 0041): a Tauri app around a web build. The exporter writes the web build
// to `<out>/web/` and a generated Tauri project to `<out>/src-tauri/` whose window loads it; `tauri
// build` (Rust toolchain needed) then makes installers. The project is generated, not copied from
// the editor's src-tauri/: a game needs only the fs plugin, for saves in its app data folder
// (ADR 0024), native gamepads (ADR 0335: src-tauri/src/gamepad.rs, copied verbatim; node.ts reads
// it and passes its text in), and its own name, identifier, window size and icon. No file access
// here (node.ts writes the files), so the generated text is easy to test.
import type { ProjectSettingsInput } from "../engine";
import { buildSettingsProblems, type BuildSettings } from "../engine/core/buildSettings";

export type { BuildSettings };

export interface DesktopOptions {
  /** The product name (project.json's `name`). */
  name: string;
  settings: ProjectSettingsInput & { build?: BuildSettings };
  /** The text of the editor's src-tauri/src/gamepad.rs (ADR 0335), written to the project as src/gamepad.rs. */
  gamepadModule: string;
  /**
   * ADR 0376: the build has debugging on (`game.json` `debug`): the app takes a `--debug-link <address>` flag that
   * overrides `debug.link` (the shell hands it to the page before it loads). A release package has no such flag.
   */
  debug?: boolean;
  /**
   * ADR 0403 (pairing plan O2): the sources of the debug link's listener crates, by path under `src-tauri/vendor/`
   * (`ws-listener/Cargo.toml`, `ws-listener/src/lib.rs`, `debug-link-tauri/…`), read from native/ by node.ts. With `debug`, the
   * project gets them as path dependencies (`tauri build` compiles them), `lib.rs` manages `DebugLinkListeners` and `DebugDiscovery` and registers
   * the `myco_debuglink_*` commands. A release package, or a debug one given none, has no listener.
   */
  debugListener?: ReadonlyMap<string, string>;
}

