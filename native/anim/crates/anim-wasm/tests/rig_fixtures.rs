//! The Node test's rig fixtures (T40, `src/plugins/animation/runtime/wasm/fixtures/`): the rig
//! test skeleton (`rig.skel`), a graph with one two-bone IK node on the left leg fed by target
//! slot 0 (`rig_ik.animgraph`), and what the native core shows for a world-space target with the
//! character moved and turned (`rig_expected.json`). The Node test (`rig.node.test.ts`) writes the
//! same rig input rows through the built wasm and compares; the core is deterministic (no FMA, no
//! relaxed SIMD), so the tolerance is 1e-5 on matrix entries (f32 printing). Also the Node
//! benchmark's rig graph (`loco_rig.animgraph`, `bench.mjs`): T31's locomotion graph with a
//! two-foot grounder and a look-at over the 60-bone humanoid (ADR 0370's budget shape).
//!
//! The files are committed; this test fails when they are stale. Regenerate with
//! `MYCO_UPDATE_FIXTURES=1 cargo test -p anim-wasm --test rig_fixtures`.

mod common;

