//! The Node test's retarget fixtures (T41, `src/plugins/animation/runtime/wasm/fixtures/`): two
//! humanoid skeletons (T-pose with Y-along bones; A-pose with X-along bones, shorter legs), a
//! walking clip on the first, a source graph playing it, and a graph on the second whose output is
//! a `RETARGET` node pinning every IK goal; with what the native core shows after a number of
//! frames (bone matrices) and the bone maps `guess_bone_map` gives. The Node test
//! (`retarget.node.test.ts`) guesses the maps, creates the map and runs the frames through the
//! built wasm and compares; the core is deterministic, so the tolerance is 1e-5 (f32 printing).
//!
//! The files are committed; this test fails when they are stale. Regenerate with
//! `MYCO_UPDATE_FIXTURES=1 cargo test -p anim-wasm --test retarget_fixtures`.

mod common;
mod rigs;

use std::fmt::Write as _;
use std::fs;
use std::path::PathBuf;

use anim_format::graph::family;
use anim_format::NONE;
use anim_graph::retarget::{kind, RetargetParams, MAX_GOALS};
use anim_retarget::RootAxis;
use common::graph::*;
use common::*;
use rigs::*;

const DT: f32 = 1.0 / 30.0;
const MAX_BONES: u32 = 64;
const FRAMES: usize = 24;

fn dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../../../../src/plugins/animation/runtime/wasm/fixtures")
}

fn list<T: std::fmt::Display>(v: &[T]) -> String {
    v.iter()
        .map(|x| x.to_string())
        .collect::<Vec<_>>()
        .join(",")
}

fn generate() -> Vec<(&'static str, Vec<u8>)> {
    let src = humanoid(Build {
        axes: Axes::YAlong,
        ..Build::default()
    });
    let tgt = humanoid(Build {
        axes: Axes::XAlong,
        arm_drop: 0.6,
        leg: 0.8,
        body: 1.1,
        spine: 2,
    });
    let (src_model, src_file) = skeleton_file(&src, false, false);
    let (_, tgt_file) = skeleton_file(&tgt, false, false);
    let clip = raw_clip(&src_model, &ClipSpec::new(1.0, true, 77));

    let mut sb = Builder::new();
    let p = sb.player("walk");
    let source_graph = sb.build(p);
    let clip_id = sb.s("walk");

    let mut core = core(4, MAX_BONES);
    let ss = core.load_skeleton(&src_file);
    let ts = core.load_skeleton(&tgt_file);
    let roles = anim_retarget::Profile::humanoid().roles.len();
    let guess = |core: &mut anim_wasm::init::Core, file: &[u8]| {
        let mut bones = vec![0u16; roles];
        let mut conf = vec![0f32; roles];
        core.guess_bone_map(file, 0, &mut bones, &mut conf);
        bones
    };
    let src_map = guess(&mut core, &src_file);
    let tgt_map = guess(&mut core, &tgt_file);
    assert_eq!(src_map, src.map.bones);
    let map = core.retarget_map_create(
        ss,
        0,
        &src_map,
        ts,
        0,
        &tgt_map,
        anim_wasm::retarget::MAP_ALIGN,
    );
    assert_ne!(map, 0);
    let goals_n = core.retarget_goal_count(map) as usize;
    let mut goals = [(0.0, NONE); MAX_GOALS];
    goals[..goals_n].fill((1.0, NONE));
    let params = RetargetParams {
        map: 0,
        graph: 1,
        state_capacity: 4096,
        depth_capacity: 2,
        param_capacity: 4,
        root_axes: [RootAxis::Scaled, RootAxis::Unscaled, RootAxis::Scaled],
        goals,
        goal_count: goals_n,
    };
    let mut rb = Builder::new();
    let (map_id, src_id) = (rb.s("map"), rb.s("src"));
    let node = rb.node(family::RETARGET, kind::RETARGET, &[], &params.words());
    let graph = rb.build(node);

    let c = core.load_clip(&clip);
    let sg = core.load_graph(&source_graph);
    assert_eq!(core.graph_bind(sg, clip_id, c), 0);
    let (_, h) = instance(&mut core, &graph, ts, &[(map_id, map), (src_id, sg)]);
    for _ in 0..FRAMES {
        frame(&mut core, DT);
    }
    let m = matrices(&core, h, MAX_BONES as usize, tgt.n());

    let mut json = String::new();
    json.push_str("{\n  \"note\": \"Generated by native/anim/crates/anim-wasm/tests/retarget_fixtures.rs from the native core. Do not edit.\",\n");
    let _ = writeln!(json, "  \"maxBones\": {MAX_BONES},");
    let _ = writeln!(json, "  \"bones\": {},", tgt.n());
    let _ = writeln!(json, "  \"dt\": {DT},");
    let _ = writeln!(json, "  \"frames\": {FRAMES},");
    json.push_str("  \"tolerance\": 0.00001,\n");
    let _ = writeln!(json, "  \"alignFlag\": {},", anim_wasm::retarget::MAP_ALIGN);
    let _ = writeln!(json, "  \"goals\": {goals_n},");
    let _ = writeln!(
        json,
        "  \"binds\": {{\"clip\": {clip_id}, \"map\": {map_id}, \"src\": {src_id}}},"
    );
    let _ = writeln!(json, "  \"srcMap\": [{}],", list(&src_map));
    let _ = writeln!(json, "  \"tgtMap\": [{}],", list(&tgt_map));
    let _ = writeln!(json, "  \"matrices\": [{}]", list(&m));
    json.push_str("}\n");
    vec![
        ("retarget_src.skel", src_file),
        ("retarget_tgt.skel", tgt_file),
        ("retarget_walk.anim", clip),
        ("retarget_source.animgraph", source_graph),
        ("retarget.animgraph", graph),
        ("retarget_expected.json", json.into_bytes()),
    ]
}

#[test]
fn retarget_fixtures_are_up_to_date() {
    let files = generate();
    let update = std::env::var_os("MYCO_UPDATE_FIXTURES").is_some();
    let dir = dir();
    let mut stale = Vec::new();
    for (name, bytes) in &files {
        let path = dir.join(name);
        if fs::read(&path).ok().as_deref() != Some(bytes.as_slice()) {
            stale.push(*name);
            if update {
                fs::write(&path, bytes).unwrap();
            }
        }
    }
    assert!(
        update || stale.is_empty(),
        "stale fixtures {stale:?}: run MYCO_UPDATE_FIXTURES=1 cargo test -p anim-wasm --test retarget_fixtures"
    );
}
