//! The Node test's fixtures (`src/plugins/animation/runtime/wasm/fixtures/`): a skeleton and two
//! clips, with the bone matrices `anim-offline` expects for the playback the Node test runs
//! through the built wasm (`core.node.test.ts`), plus a 60-bone humanoid and two clips for the
//! Node benchmark (`native/anim/crates/anim-wasm/bench.mjs`).
//!
//! The files are generated here (anim-format writers, anim-compress, deterministic) and
//! committed. This test fails when they are stale; regenerate with
//! `MYCO_UPDATE_FIXTURES=1 cargo test -p anim-wasm --test fixtures`. It also runs the same
//! playback through the native core and checks it against the same expectations.

mod common;

use std::fmt::Write as _;
use std::fs;
use std::path::PathBuf;

use anim_wire::core::*;
use common::*;

const DT: f32 = 1.0 / 30.0;
const MAX_BONES: u32 = 64;
/// Bone-matrix tolerance against the f64 reference: see `tests/core.rs` (a few f32 ulps per
/// operation over the chain; 1e-4 leaves an order of magnitude of margin).
const TOLERANCE: f64 = 1e-4;

fn dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../../../../src/plugins/animation/runtime/wasm/fixtures")
}

struct Files(Vec<(&'static str, Vec<u8>)>);

fn json_floats(out: &mut String, v: &[f64]) {
    out.push('[');
    for (i, x) in v.iter().enumerate() {
        if i > 0 {
            out.push(',');
        }
        let _ = write!(out, "{}", *x as f32);
    }
    out.push(']');
}

fn generate() -> (Files, Vec<f64>, Vec<f64>) {
    let (skel, skel_bytes) = skeleton(Shape::Tree(12), 7);
    let walk = clip_with_event(&skel, 2.0, true, 11, 0.2);
    let run = clip(&skel, 1.0, true, 12);
    let r = Reference::new(&skel_bytes);
    // Case "play": walk from 0, 10 frames.
    let play = r.matrices(&r.sample(&walk, 10.0 * DT as f64));
    // Case "crossfade": then run with a 0.5 s fade, 6 frames: walk at 16 frames, run at 6, weight 0.4.
    let blended = anim_offline::pose::lerp(
        &r.sample(&walk, 16.0 * DT as f64),
        &r.sample(&run, 6.0 * DT as f64),
        6.0 * DT as f64 / 0.5,
    );
    let crossfade = r.matrices(&blended);

    let (human, human_bytes) = skeleton(Shape::Humanoid, 3);
    let h_walk = clip(&human, 1.0, true, 31);
    let h_run = clip(&human, 1.0, true, 32);

    let mut json = String::new();
    json.push_str("{\n  \"note\": \"Generated by native/anim/crates/anim-wasm/tests/fixtures.rs from anim-offline (f64). Do not edit.\",\n");
    let _ = writeln!(json, "  \"maxBones\": {MAX_BONES},");
    let _ = writeln!(json, "  \"bones\": {},", skel.bones.len());
    let _ = writeln!(json, "  \"dt\": {DT},");
    let _ = writeln!(json, "  \"tolerance\": {TOLERANCE},");
    json.push_str("  \"eventTime\": 0.2,\n");
    json.push_str("  \"play\": ");
    json_floats(&mut json, &play);
    json.push_str(",\n  \"crossfade\": ");
    json_floats(&mut json, &crossfade);
    json.push_str("\n}\n");

    (
        Files(vec![
            ("small.skel", skel_bytes),
            ("walk.anim", walk),
            ("run.anim", run),
            ("humanoid.skel", human_bytes),
            ("humanoid_walk.anim", h_walk),
            ("humanoid_run.anim", h_run),
            ("expected.json", json.into_bytes()),
        ]),
        play,
        crossfade,
    )
}

#[test]
fn fixtures_are_up_to_date_and_the_native_core_matches_them() {
    let (files, play_expected, crossfade_expected) = generate();
    let update = std::env::var_os("MYCO_UPDATE_FIXTURES").is_some();
    let dir = dir();
    let mut stale = Vec::new();
    for (name, bytes) in &files.0 {
        let path = dir.join(name);
        if fs::read(&path).ok().as_deref() != Some(bytes.as_slice()) {
            stale.push(*name);
            if update {
                fs::create_dir_all(&dir).unwrap();
                fs::write(&path, bytes).unwrap();
            }
        }
    }
    assert!(
        update || stale.is_empty(),
        "stale fixtures {stale:?}: run MYCO_UPDATE_FIXTURES=1 cargo test -p anim-wasm --test fixtures"
    );

    // The same playback as the Node test, natively.
    let get = |n: &str| files.0.iter().find(|f| f.0 == n).unwrap().1.clone();
    let mut core = core(4, MAX_BONES);
    let s = core.load_skeleton(&get("small.skel"));
    let walk = core.load_clip(&get("walk.anim"));
    let run = core.load_clip(&get("run.anim"));
    let h = core.create_instance(0, s, 0);
    send(&mut core, &[play(h, walk, 0, 0.0, 1, 0)]);
    for _ in 0..10 {
        core.write_inputs(0);
        core.evaluate(0, PASS_NORMAL, DT, DT);
    }
    let bones = play_expected.len() / 12;
    let d = max_diff(
        &matrices(&core, h, MAX_BONES as usize, bones),
        &play_expected,
    );
    assert!(d < TOLERANCE, "play: {d}");
    send(&mut core, &[play(h, run, 0, 0.5, 2, 0)]);
    core.evaluate(0, PASS_NORMAL, DT, DT);
    for _ in 0..5 {
        core.write_inputs(0);
        core.evaluate(0, PASS_NORMAL, DT, DT);
    }
    let d = max_diff(
        &matrices(&core, h, MAX_BONES as usize, bones),
        &crossfade_expected,
    );
    assert!(d < TOLERANCE, "crossfade: {d}");
}
